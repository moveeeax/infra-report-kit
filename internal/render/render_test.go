func renderSample(t *testing.T, brand Branding) string {
	t.Helper()
	rep := sampleReport()
	narr := narrative.Render("## Recommendation\n\nClose the **bastion** first.")
	var buf bytes.Buffer
	if err := HTML(&buf, BuildView(rep, brand, model.Sections, narr)); err != nil {
		t.Fatalf("HTML: %v", err)
	}
	return buf.String()
}

func defaultBrand() Branding {
	return Branding{Name: "Northwind Cloud Services", PrimaryColor: "#0B2545",
		AccentColor: "#0B5FFF", Contact: "service-desk@northwind.example",
		Footer: "Confidential."}
}

func TestHTMLContainsTheReportSubstance(t *testing.T) {
	got := renderSample(t, defaultBrand())
	for _, want := range []string{
		"Northwind Cloud Services",
		"Acme Retail",
		"123456789012",
		"2026-06",
		"$7,927.43",              // spend, with thousands separator
		"+$698.81",               // month-over-month delta
		"Amazon Bedrock",         // a service with no previous spend still appears
		"sev-critical",           // severity badge
		"Security group sg-0aa1", // finding title
		"Replace 0.0.0.0/0",      // recommendation
		"Orphaned NAT gateway removed",
		"$47.30",
		"99.745%",
		"<strong>bastion</strong>", // narrative markdown
		"Confidential.",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("rendered report is missing %q", want)
		}
	}
}

