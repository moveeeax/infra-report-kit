// TestPDFDrivesAnExternalCommand uses cp as a stand-in renderer. It proves the
// argv substitution and the "did it actually write anything" check, which is
// all this package owns — the real renderer is a headless browser the operator
// supplies.
func TestPDFDrivesAnExternalCommand(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "report.html")
	out := filepath.Join(dir, "report.pdf")
	if err := os.WriteFile(in, []byte("<html></html>"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := PDF(context.Background(), []string{"cp", "{{input}}", "{{output}}"}, in, out); err != nil {
		t.Fatalf("PDF: %v", err)
	}
	if st, err := os.Stat(out); err != nil || st.Size() == 0 {
		t.Fatalf("renderer produced no output: %v", err)
	}
}

func TestPDFFailsWhenTheRendererWritesNothing(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "report.html")
	if err := os.WriteFile(in, []byte("<html></html>"), 0o600); err != nil {
		t.Fatal(err)
	}
	// true(1) exits 0 and writes nothing: exactly the silent failure that
	// would otherwise email a client a zero-byte PDF.
	err := PDF(context.Background(), []string{"true", "{{input}}", "{{output}}"},
		in, filepath.Join(dir, "report.pdf"))
	if err == nil {
		t.Fatal("want an error when the renderer exits cleanly but writes no PDF")
	}
	if !strings.Contains(err.Error(), "wrote no output") {
		t.Errorf("error = %v, want it to name the empty output", err)
	}
}

