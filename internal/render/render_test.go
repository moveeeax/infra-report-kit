func TestWithThousands(t *testing.T) {
	cases := map[string]string{
		"0.00":       "0.00",
		"999.99":     "999.99",
		"1000.00":    "1,000.00",
		"7927.43":    "7,927.43",
		"1234567.89": "1,234,567.89",
	}
	for in, want := range cases {
		if got := withThousands(in); got != want {
			t.Errorf("withThousands(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestBrandingFromInlinesLogo(t *testing.T) {
	dir := t.TempDir()
	logo := filepath.Join(dir, "logo.svg")
	if err := os.WriteFile(logo, []byte(`<svg xmlns="http://www.w3.org/2000/svg"/>`), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg := &config.Config{Tenant: config.Tenant{Name: "N", LogoPath: "logo.svg"}}
	cfg.SetDir(dir)

	b, err := BrandingFrom(cfg)
	if err != nil {
		t.Fatalf("BrandingFrom: %v", err)
	}
	if !strings.HasPrefix(string(b.LogoDataURI), "data:image/svg+xml;base64,") {
		t.Errorf("logo was not inlined as a data URI: %q", b.LogoDataURI)
	}
	if b.PrimaryColor != defaultPrimary || b.AccentColor != defaultAccent {
		t.Errorf("missing colours must fall back to defaults, got %q/%q", b.PrimaryColor, b.AccentColor)
	}
}

