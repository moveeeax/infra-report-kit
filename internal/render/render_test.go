func TestSectionOrderIsHonoured(t *testing.T) {
	rep := sampleReport()
	var buf bytes.Buffer
	order := []model.Section{model.SectionSecurity, model.SectionCost}
	if err := HTML(&buf, BuildView(rep, defaultBrand(), order, "")); err != nil {
		t.Fatal(err)
	}
	got := buf.String()
	sec, cost := strings.Index(got, "<h2>Security</h2>"), strings.Index(got, "<h2>Cost</h2>")
	if sec < 0 || cost < 0 {
		t.Fatalf("sections missing (security %d, cost %d)", sec, cost)
	}
	if sec > cost {
		t.Error("configured section order was not honoured")
	}
	if strings.Contains(got, "<h2>Reliability</h2>") {
		t.Error("a section left out of section_order must not be rendered")
	}
}

